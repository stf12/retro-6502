#!/usr/bin/env python3
"""Generate a MAME -autoboot_script (Lua) that types a text file into the
Apple I one line at a time, pausing after every RETURN.

Why: the Apple I keyboard latches a single character. While BASIC (or the
Woz Monitor) is busy with a line it just received, MAME's fast typing
loses characters -- typically the first one of the next line.

Usage:
  txt2lua.py PROG.txt -o build/autotype.lua [--pre "EFFF: E0" --pre E000R]
             [--post RUN] [--delay 20]
--pre/--post lines are typed before/after the file. --delay is the pause
after each line, in frames (60 = 1 second).
"""
import argparse


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


ap = argparse.ArgumentParser()
ap.add_argument("textfile", nargs="?")
ap.add_argument("-o", "--output", required=True)
ap.add_argument("--pre", action="append", default=[])
ap.add_argument("--post", action="append", default=[])
ap.add_argument("--delay", type=int, default=20)
a = ap.parse_args()

body = []
if a.textfile:
    text = open(a.textfile, encoding="latin-1").read()
    body = [l.rstrip() for l in text.replace("\r\n", "\n").replace("\r", "\n").upper().split("\n")]
    body = [l for l in body if l]
lines = [""] + a.pre + body + a.post      # "" = a first RETURN for a fresh line

lua = f"""-- generated by tools/txt2lua.py
local lines = {{
{",".join(chr(10) + "  " + lua_str(l) for l in lines)}
}}
local delay = {a.delay}
local nk = manager.machine.natkeyboard
local i, wait = 1, 60   -- let the machine settle for 1 s first
local sub
sub = emu.add_machine_frame_notifier(function()
  if wait > 0 then wait = wait - 1; return end
  if not nk.empty then return end          -- previous line still being typed
  if i > #lines then sub = nil; return end
  nk:post(lines[i] .. "\\n")
  i = i + 1
  wait = delay + #lines[i - 1]
end)
"""
with open(a.output, "w") as f:
    f.write(lua)
print(f"{a.output}: {len(lines)} lines, {a.delay} frames after each")
